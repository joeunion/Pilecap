def index_page(pages: Mapping[str, int]) -> str:
    """The index: the guides, then one line per module page with its count."""
    body = ["## Guides", ""]
    body += [f"- [{title}]({file})" for file, title, _f in EXTRA]
    body += ["", "## Modules", ""]
    body += [f"- [`{m}`]({m}.md) — {n} export{'s' * (n != 1)}" for m, n in pages.items()]
    body += ["", f"{sum(pages.values())} exports in {len(pages)} modules."]
    lead = (
        "The map of the SDK for a product builder: read this first. Every name here is in "
        "`pilecap`'s `__all__` exactly once."
    )
    return _page("The Pilecap SDK reference", lead, body)


def build(root: Path) -> tuple[dict[str, str], list[str]]:
    """Every page's text by file name, and every export with no contract line."""
    found = entries(root)
    missing = [
        f"{e.name} ({e.source}) has no contract line"
        for es in found.values()
        for e in es
        if not e.contract
    ]
    if missing:
        return {}, missing
    rules, goldens = rule_mentions(root), golden_uses(root)
    pages = {f"{m}.md": module_page(m, es, rules, goldens) for m, es in found.items()}
    pages.update({file: render(root) for file, _t, render in EXTRA})
    pages["reference.md"] = index_page({m: len(es) for m, es in found.items()})
    return pages, []


def main(argv: Sequence[str], root: Path | None = None) -> int:
    """`--reference [--check]` writes `docs/sdk/`, or exits 1 when it differs."""
    parser = argparse.ArgumentParser(prog="python -m quality.sdk --reference")
    parser.add_argument("--reference", action="store_true")
    parser.add_argument("--check", action="store_true", help="exit 1 when docs/sdk/ is stale")
    parser.add_argument("--root", type=Path, default=None)
    args = parser.parse_args(list(argv))
    home = (args.root or root or ROOT).resolve()
    try:
        pages, missing = build(home)
    except CouldNotLook as exc:
        exit_could_not_look(str(exc))
    for line in missing:
        print(f"reference: {line}")
    if missing:
        print(f"reference: not written — {len(missing)} export(s) have no contract line")
        return 1
    folder = home / HOME
    have = {p.name: p.read_text() for p in folder.glob("*.md")} if folder.is_dir() else {}
    stale = sorted(set(have) ^ set(pages) | {f for f in pages if have.get(f) != pages[f]})
    if args.check:
        for file in stale:
            print(f"reference: {HOME}/{file} differs — run {REGENERATE}")
        print(f"reference: {'STALE' if stale else 'current'} · {len(pages)} pages")
        return 1 if stale else 0
    if folder.is_dir():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    for file, text in pages.items():
        (folder / file).write_text(text)
    print(f"reference: wrote {HOME}/ · {len(pages)} pages")
    return 0
