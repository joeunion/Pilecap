def scaffold_writes(root: Path) -> list[str]:
    """Each file `scaffold` writes outside `apps/<app>/`, its path lifted from the constant."""
    source = (root / SCAFFOLD).read_text()
    tree = ast.parse(source)
    named = {
        node.right.id
        for node in ast.walk(tree)
        if isinstance(node, ast.BinOp)
        and isinstance(node.op, ast.Div)
        and isinstance(node.left, ast.Name)
        and node.left.id == "root"
        and isinstance(node.right, ast.Name)
        and node.right.id.isupper()
    }
    listed = {name for name, _said in SCAFFOLD_WRITES}
    unlisted = sorted(named - listed - SCAFFOLD_READS)
    if unlisted:
        raise CouldNotLook(
            f"reference: {SCAFFOLD} writes root / {', '.join(unlisted)}, which the one path's "
            "list of what scaffold writes outside apps/<app>/ does not name (SCAFFOLD_WRITES)"
        )
    rows = []
    for name, said in SCAFFOLD_WRITES:
        node = _node(tree, name)
        value = getattr(node, "value", None)
        if node is None or not isinstance(value, ast.Constant) or not isinstance(value.value, str):
            raise CouldNotLook(f"reference: {SCAFFOLD} no longer binds {name} to a path")
        rows.append(f"- `{value.value}` — {said} (`{SCAFFOLD}:{node.lineno}`)")
    return rows


