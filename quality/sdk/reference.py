def field_types(root: Path) -> list[str]:
    """The keys of `scaffold`'s closed `FIELD_TYPES`, read by AST, in their order."""
    tree = ast.parse((root / SCAFFOLD).read_text())
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "FIELD_TYPES":
            if isinstance(node.value, ast.Dict):
                return [
                    k.value
                    for k in node.value.keys
                    if isinstance(k, ast.Constant) and isinstance(k.value, str)
                ]
    raise CouldNotLook(f"reference: {SCAFFOLD} no longer declares FIELD_TYPES as a dict")


def _filled(said: str, fill: Mapping[str, str]) -> str:
    for name, value in fill.items():
        said = said.replace(f"{{{name}}}", value)
    return said


def _sections(
    root: Path, spec: Sequence[tuple[str, Sequence[tuple[str, str, str, str]]]], **fill: str
) -> list[str]:
    """`## section` then its pointed rows, per section; `{name}` in a sentence takes `fill`."""
    body: list[str] = []
    for section, rows in spec:
        said = [(w, _filled(s, fill), p, a) for w, s, p, a in rows]
        body += [f"## {section}", "", *_pointed(root, said), ""]
    return body


