def listed(root: Path) -> list[str]:
    """Every export heading across `docs/sdk/`, in page order — duplicates kept."""
    home = root / HOME
    if not home.is_dir():
        return []
    return [n for page in sorted(home.glob("*.md")) for n in HEADING.findall(page.read_text())]


def judge(root: Path) -> list[tuple[str, str]]:
    """Rule 97's reference half: `(path, why)` per export absent, doubled or stale."""
    files = {m: p.relative_to(root).as_posix() for m, p, _t in facade_modules(root)}
    exported: dict[str, str] = {}
    out: list[tuple[str, str]] = []
    for module, _t in public_modules(root):
        names = declared_all(parse(root / files[module])) or []
        for name, n in sorted(Counter(names).items()):
            exported[f"{module}.{name}"] = files[module]
            if n > 1:
                out.append(
                    (files[module], f"{module}.{name} is exported twice — every export once")
                )
    have = Counter(listed(root))
    for full, rel in sorted(exported.items()):
        if not have[full]:
            out.append((rel, f"{full} is exported and absent from {HOME}/ — run {REGENERATE}"))
        elif have[full] > 1:
            out.append((HOME, f"{full} is listed {have[full]} times in {HOME}/ — run {REGENERATE}"))
    for full in sorted(set(have) - set(exported)):
        out.append((HOME, f"{full} is in {HOME}/ and no longer exported — run {REGENERATE}"))
    return out


def _node(tree: ast.Module, attr: str) -> ast.stmt | None:
    """The statement binding `attr` — the last, so an `@overload` stack reads its implementation."""
    found: ast.stmt | None = None
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if node.name == attr:
                found = node
        elif isinstance(node, (ast.Assign, ast.AnnAssign, ast.TypeAlias)):
            names = [t.id for t in getattr(node, "targets", []) if isinstance(t, ast.Name)]
            target = getattr(node, "target", None) or getattr(node, "name", None)
            if isinstance(target, ast.Name):
                names.append(target.id)
            if attr in names and found is None:
                found = node
    return found


def _first(text: str | None) -> str:
    """A docstring's first paragraph, its lines joined — the contract a wrapped line would cut."""
    head = (text or "").strip().split("\n\n", 1)[0]
    return " ".join(line.strip() for line in head.splitlines() if line.strip())


def _value_contract(tree: ast.Module, node: ast.stmt, lines: list[str]) -> str:
    """A value's `#:` comment block's first paragraph, else the string statement right after it."""
    at, block = node.lineno - 2, list[str]()
    while at >= 0 and lines[at].strip().startswith("#:"):
        block.insert(0, lines[at].strip()[2:].strip())
        at -= 1
    if block:
        return _first("\n".join(block))
    after = tree.body.index(node) + 1
    if after < len(tree.body):
        nxt = tree.body[after]
        if isinstance(nxt, ast.Expr) and isinstance(nxt.value, ast.Constant):
            return _first(str(nxt.value.value))
    return ""


def defined_at(root: Path, module: str, name: str) -> tuple[str, str]:
    """(`file:line`, contract line) of the object `module.name` reaches; `""` when it has none."""
    key = resolve(root, module, name)
    if key is None:
        return f"{module_file(root, module)}", ""
    own = module_file(root, key)
    if own is not None:
        return f"{own.relative_to(root).as_posix()}:1", _first(ast.get_docstring(parse(own)))
    home, _, attr = key.rpartition(".")
    path = module_file(root, home)
    if path is None:
        return key, ""
    tree = parse(path)
    node = _node(tree, attr)
    rel = path.relative_to(root).as_posix()
    if node is None:
        return rel, ""
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        contract = _first(ast.get_docstring(node))
    else:
        contract = _value_contract(tree, node, path.read_text().splitlines())
        value = getattr(node, "value", None)
        if not contract and home.endswith(".events") and isinstance(value, ast.Constant):
            contract = f"The event name `{value.value!s}`."
    return f"{rel}:{node.lineno}", contract


def facade_lines(root: Path, module: str) -> dict[str, str]:
    """The `#: <Name> — <contract>` lines a facade module carries, by name."""
    path = module_file(root, module)
    return dict(_FACADE_LINE.findall(path.read_text())) if path is not None else {}


def entries(root: Path) -> dict[str, list[Entry]]:
    """Per public module, its exports from the surface record, each with source and contract."""
    record = root / SURFACE
    if not record.is_file():
        raise CouldNotLook(f"{SURFACE} is absent — run python -m quality.sdk --surface")
    names = load(record.read_text(), SURFACE).get("names") or {}
    modules = sorted((m for m, _t in public_modules(root)), key=len, reverse=True)
    out: dict[str, list[Entry]] = {m: [] for m, _t in public_modules(root)}
    for full, entry in sorted(names.items()):
        module = next(
            m for m in modules if full.startswith(f"{m}.") and "." not in full[len(m) + 1 :]
        )
        short = full[len(module) + 1 :]
        source, contract = defined_at(root, module, short)
        contract = contract or facade_lines(root, module).get(short, "")
        sig = entry.get("sig") or ""
        out[module].append(Entry(full, entry.get("kind", ""), sig, source, contract))
    return {m: es for m, es in out.items() if es}


def rule_mentions(root: Path) -> dict[str, list[str]]:
    """Per backticked word in `rules.yaml`, the house rules whose text says it."""
    text = (root / RULES).read_text() if (root / RULES).is_file() else ""
    marks = list(_RULE.finditer(text))
    out: dict[str, list[str]] = {}
    for i, mark in enumerate(marks):
        body = text[mark.end() : marks[i + 1].start() if i + 1 < len(marks) else len(text)]
        words = {w for span in _TICKED.findall(body) for w in _WORD.findall(span)}
        for word in words:
            out.setdefault(word, []).append(mark.group(1))
    return out


def golden_uses(root: Path) -> dict[str, list[str]]:
    """Per `pilecap.<module>.<name>`, the goldens whose files import it."""
    out: dict[str, set[str]] = {}
    home = root / GOLDENS
    for path in sorted(home.rglob("*")) if home.is_dir() else []:
        if not path.is_file():
            continue
        golden = path.relative_to(home).parts[0]
        for module, names in _IMPORT.findall(path.read_text(errors="replace")):
            for part in names.strip("()").split(","):
                word = part.split(" as ")[0].strip()
                if word.isidentifier():
                    out.setdefault(f"{module}.{word}", set()).add(golden)
    return {k: sorted(v) for k, v in out.items()}


# --- the pages ------------------------------------------------------------------------------------


def _page(title: str, lead: str, body: list[str]) -> str:
    return "\n".join([f"# {title}", "", _GENERATED, "", lead, "", *body]).rstrip() + "\n"


def module_page(
    module: str, es: list[Entry], rules: Mapping[str, list[str]], goldens: Mapping[str, list[str]]
) -> str:
    """One `pilecap.<module>` page: per export its contract, signature, source, rules, goldens."""
    body: list[str] = []
    for e in es:
        short = e.name.rpartition(".")[2]
        body += [f"### `{e.name}`", "", e.contract, ""]
        body.append(f"- {e.kind}{f' `{e.sig}`' if e.sig else ''} · source `{e.source}`")
        if rules.get(short):
            body.append(f"- house rules naming it: {', '.join(rules[short])}")
        if goldens.get(e.name):
            body.append(f"- golden: {', '.join(f'`{g}`' for g in goldens[e.name])}")
        body.append("")
    lead = f"{len(es)} export{'s' * (len(es) != 1)}. Import them as `from {module} import <name>`."
    return _page(f"`{module}`", lead, body)


def _resolve(root: Path, path: str, anchor: str) -> str:
    """`path:line` of the first line holding `anchor`, line-less in a file the scaffold grows."""
    file = root / path
    lines = file.read_text().splitlines() if file.is_file() else []
    hit = next((n for n, line in enumerate(lines, 1) if anchor in line), None)
    if hit is None:
        raise CouldNotLook(f"reference: {path} no longer holds {anchor!r} — the page points at it")
    return f"`{path}`" if path in _scaffold_grown(root) else f"`{path}:{hit}`"


def _scaffold_grown(root: Path) -> frozenset[str]:
    """The paths `SCAFFOLD_WRITES` names, whose lines a product's own `scaffold` moves."""
    tree = ast.parse((root / SCAFFOLD).read_text())
    nodes = [_node(tree, name) for name, _said in SCAFFOLD_WRITES]
    values = [getattr(node, "value", None) for node in nodes]
    return frozenset(
        v.value for v in values if isinstance(v, ast.Constant) and isinstance(v.value, str)
    )


def _pointed(root: Path, rows: Sequence[tuple[str, str, str, str]]) -> list[str]:
    """`- **what** — sentence (`file:line`)` per row, each pointer resolved on this tree."""
    return [
        f"- **{what}** — {said} ({_resolve(root, path, anchor)})"
        for what, said, path, anchor in rows
    ]


