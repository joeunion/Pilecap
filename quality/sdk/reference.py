def plant_names() -> set[str]:
    """Every name a canary plant carries — the census `scaffold`'s `refuse_plants` reads."""
    plants = importlib.import_module("quality.engine.plants")
    found: set[str] = set()
    for path in plants.plant_collision_population(plants.RULES):
        declared, _, _ = plants.plant_declared_names(path)
        found.update(name for _, name in declared)
    return found


