#!/usr/bin/env bash
. "$(dirname -- "${BASH_SOURCE:-$0}")/bash_only.sh" || exit 2
# A typed TypeScript client for the API, from a checkout. No server needed.
#
#   ./scripts/gen_client.sh                       # -> clients/api.d.ts (+ openapi.json)
#   ./scripts/gen_client.sh path/to/api.d.ts      # somewhere else
#
# **Offline by construction, and that is the whole design choice.** The obvious
# alternative — point `openapi-typescript` at a running `/api/v1/openapi.json` — makes
# generating a client depend on somebody having `serve.sh` up, on the right port,
# against the right branch, with a database migrated. Every one of those is a way
# to generate a client for a contract that is not the one in this tree. The
# schema comes out of the checkout instead, via django-ninja's own
# `export_openapi_schema`, so the client and the code are the same commit.
#
# The generated file is a *build artifact*, not source: it belongs to whichever
# front end consumes it, and this repository ships no front end (`architecture.md`:
# bring your own). `clients/` is therefore gitignored, and the contract that IS
# committed is the OpenAPI document the server serves at /api/v1/docs.
#
# `npx` needs Node and the network the first time; that is the one thing this
# script cannot do offline, and it is why it says so rather than failing oddly.
#
# AND IT SAYS SO IN THE EXIT CODE TOO. "npx was not found" is an
# I-COULD-NOT-LOOK answer, and it used to be reported with exit 1 — the code a
# caller reads as "I looked, and it is wrong". A build step that treats the two
# alike ships a stale client on the day Node is missing from the runner and
# calls it a lint failure. Exit 2 is "could not look" everywhere in this
# repository (`docs/product/instruments.md`), and this script is no exception:
# 2 for an absent tool, 1 for a schema this checkout genuinely cannot export.
set -euo pipefail

cd "$(dirname "$0")/.."

if [ -f scripts/db.sh ]; then
    # shellcheck source=scripts/db.sh
    source scripts/db.sh
fi

export DJANGO_SETTINGS_MODULE="${DJANGO_SETTINGS_MODULE:-config.settings.local}"

OUTPUT="${1:-clients/api.d.ts}"
SCHEMA="${SCHEMA:-clients/openapi.json}"
# Pinned rather than `@latest`: a generator that changes between two runs
# produces a diff nobody wrote, in a file people read to answer "what does the
# API return".
OPENAPI_TYPESCRIPT="${OPENAPI_TYPESCRIPT:-openapi-typescript@7.9.1}"

mkdir -p "$(dirname "$OUTPUT")" "$(dirname "$SCHEMA")"

# The output directory ignores itself, rather than the repository ignoring it.
# A generated client is a build artifact of whatever tree it was generated from;
# committing one means the next person reads a contract that may be two branches
# old. Writing the rule here also means the directory carries it wherever it is
# pointed, instead of `.gitignore` having to learn every path anyone chooses.
if [ ! -e "$(dirname "$OUTPUT")/.gitignore" ]; then
    printf '# Generated by scripts/gen_client.sh. A build artifact, never source.\n*\n' \
        > "$(dirname "$OUTPUT")/.gitignore"
fi

echo "Exporting the OpenAPI document from this checkout..."
# `--api` is explicit: the resolver's fallback looks for a NinjaAPI mounted at
# `/api/`, and this project mounts at `/api/v1/` on purpose.
uv run python manage.py export_openapi_schema --api config.api.api --indent 2 --output "$SCHEMA"
echo "  -> $SCHEMA"

if ! command -v npx >/dev/null 2>&1; then
    # Exit 2: I could not look. See the header — this is an absent tool, not a
    # client that came out wrong.
    echo "" >&2
    echo "npx was not found, so the TypeScript client was not generated." >&2
    echo "The OpenAPI document above is complete and is what a generator reads." >&2
    echo "Install Node, then re-run — or hand $SCHEMA to whatever generator your" >&2
    echo "front end already uses." >&2
    exit 2
fi

echo "Generating the TypeScript client with ${OPENAPI_TYPESCRIPT}..."
npx --yes "$OPENAPI_TYPESCRIPT" "$SCHEMA" --output "$OUTPUT"
echo "  -> $OUTPUT"
